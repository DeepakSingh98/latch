from __future__ import annotations

import json
import traceback

import torch
from torch.fx.experimental.proxy_tensor import make_fx

from megakernel_lab.operation_compiler.random import (ADVANCE_TARGET, MASK_TARGET, U32, U64, _philox4x32,
                     dropout, make_rng_state, philox_advance, philox_mask)


def _scalar_philox(counter, key):
    """Independent scalar oracle using arbitrary-precision products."""
    a, b, c, d = counter
    key0, key1 = key
    for _ in range(10):
        first, second = a * 0xD2511F53, c * 0xCD9E8D57
        a, b, c, d = (second >> 32) ^ b ^ key0, second & U32, (first >> 32) ^ d ^ key1, first & U32
        key0, key1 = (key0 + 0x9E3779B9) & U32, (key1 + 0xBB67AE85) & U32
    return a, b, c, d


def _reference_mask(seed, counter, shape, threshold, scale):
    count = 1
    for size in shape:
        count *= size
    words = []
    for block_index in range((count + 3) // 4):
        block = (counter + block_index) & U64
        words.extend(_scalar_philox((block & U32, block >> 32, 0, 0), (seed & U32, seed >> 32)))
    return torch.tensor([scale if x >= threshold else 0.0 for x in words[:count]],
                        dtype=torch.float32).reshape(shape)


def test_random123_known_answers():
    # Public algorithm test vectors, not outputs generated by this implementation:
    # https://github.com/DEShawResearch/random123/blob/main/tests/kat_vectors
    vectors = [
        ((0, 0, 0, 0), (0, 0), (0x6627e8d5, 0xe169c58d, 0xbc57ac4c, 0x9b00dbd8)),
        ((U32,) * 4, (U32,) * 2, (0x408f276d, 0x41c83b0e, 0xa20bc7c6, 0x6d5451fd)),
        ((0x243f6a88, 0x85a308d3, 0x13198a2e, 0x03707344), (0xa4093822, 0x299f31d0),
         (0xd16cfe09, 0x94fdcceb, 0x5001e420, 0x24126ea1)),
    ]
    for counter, key, expected in vectors:
        assert _scalar_philox(counter, key) == expected
        tensors = [torch.tensor(word, dtype=torch.int64) for word in counter + key]
        actual = _philox4x32(tensors[:4], tensors[4:])
        assert tuple(int(x) for x in actual) == expected
    return {'published_vectors': len(vectors), 'exact_uint32_match': True}


def test_replay_and_global_generator_independence():
    state = make_rng_state(0xFEDCBA9876543210, (1 << 40) + 27)
    old = state.clone()
    rng_before = torch.get_rng_state().clone()
    x = torch.arange(128, dtype=torch.float32).reshape(8, 16)
    first, next_state = dropout(x, state, 0.25)
    replay, replay_state = dropout(x, state, 0.25)
    assert torch.equal(first, replay) and torch.equal(next_state, replay_state)
    assert torch.equal(state, old) and torch.equal(rng_before, torch.get_rng_state())
    expected = _reference_mask(0xFEDCBA9876543210, (1 << 40) + 27, (8, 16), 1 << 30, 4.0 / 3.0)
    assert torch.equal(first, x * expected)
    assert torch.equal(next_state, make_rng_state(0xFEDCBA9876543210, (1 << 40) + 59))
    return {'replay_bitwise': True, 'global_rng_unchanged': True, 'counter_above_fp32_exact_range': True}


def test_counter_carry_wrap_and_partial_block():
    for counter in (U32 - 1, U64 - 1):
        state = make_rng_state(0xABCDEF1234567890, counter)
        output, advanced = dropout(torch.ones((2, 5), dtype=torch.float32), state, 0.5)
        expected = _reference_mask(0xABCDEF1234567890, counter, (2, 5), 1 << 31, 2.0)
        assert torch.equal(output, expected)
        assert torch.equal(advanced, make_rng_state(0xABCDEF1234567890, (counter + 3) & U64))
        assert output.numel() == 10
    return {'low_word_carry': True, 'counter_64bit_wrap': True, 'partial_block_consumes_whole_block': True}


def test_threshold_boundary_and_zero_probability():
    state = make_rng_state(0)
    word = 0x6627e8d5
    assert philox_mask(state, [1], word, 2.0).item() == 2.0
    assert philox_mask(state, [1], word + 1, 2.0).item() == 0.0
    assert not torch.count_nonzero(philox_mask(state, [7], 1 << 32, 1.0))
    x = torch.arange(7, dtype=torch.float32)
    result, next_state = dropout(x, state, 0.0)
    assert torch.equal(result, x) and torch.equal(next_state, make_rng_state(0, 2))
    return {'unsigned_threshold_inclusive_keep': True, 'p_zero_consumes_declared_blocks': True}


def test_func_ad_fake_capture_and_dynamic_state():
    state = make_rng_state(0x123456789ABCDEF0, (1 << 35) + 9)
    x = torch.arange(12, dtype=torch.float32).reshape(3, 4) / 16 - 0.4

    def loss(value, rng):
        y, next_state = dropout(value, rng, 0.25)
        return (y * y).sum(), next_state

    differentiated = torch.func.grad_and_value(loss, argnums=0, has_aux=True)
    gm = make_fx(differentiated, tracing_mode='fake')(x, state)
    targets = [str(node.target) for node in gm.graph.nodes if node.op == 'call_function']
    assert targets.count(MASK_TARGET) == 1, targets
    assert targets.count(ADVANCE_TARGET) == 1, targets
    for counter in ((1 << 35) + 9, (1 << 48) + 200):
        dynamic = make_rng_state(0x123456789ABCDEF0, counter)
        gradient, (value, next_state) = gm(x, dynamic)
        expected_mask = _reference_mask(0x123456789ABCDEF0, counter, x.shape, 1 << 30, 4.0 / 3.0)
        torch.testing.assert_close(gradient, 2 * x * expected_mask * expected_mask, rtol=2e-6, atol=2e-7)
        torch.testing.assert_close(value, (x * expected_mask).square().sum(), rtol=2e-6, atol=2e-7)
        assert torch.equal(next_state, make_rng_state(0x123456789ABCDEF0, counter + 3))
    return {'opaque_targets': [MASK_TARGET, ADVANCE_TARGET], 'dynamic_integer_state': True,
            'advance_occurrences_in_ad_graph': targets.count(ADVANCE_TARGET)}


def test_two_calls_chain_state_and_recompute_backward():
    state = make_rng_state(19, 37)
    x = torch.arange(16, dtype=torch.float32).reshape(4, 4) / 32

    def loss(value):
        a, state1 = dropout(value, state, 0.5)
        b, state2 = dropout(a, state1, 0.5)
        return (b * b).sum(), state2

    gradient, (value, end) = torch.func.grad_and_value(loss, has_aux=True)(x)
    first = _reference_mask(19, 37, x.shape, 1 << 31, 2.0)
    second = _reference_mask(19, 41, x.shape, 1 << 31, 2.0)
    replay = first * second
    torch.testing.assert_close(gradient, 2 * x * replay.square(), rtol=0, atol=0)
    assert torch.equal(end, make_rng_state(19, 45))
    assert torch.equal(value, (x * replay).square().sum())
    # Differentiating again recomputes the same old masks, not new random draws.
    second_derivative = torch.func.grad(lambda v: torch.func.grad(lambda z: loss(z)[0])(v).sum())(x)
    assert torch.equal(second_derivative, 2 * replay.square())
    return {'sequential_state_consumption': 8, 'first_and_second_derivative_fixed_mask': True}


def test_operator_schema_and_fake_contract():
    state = make_rng_state(123)
    checks = ('test_schema', 'test_faketensor')
    mask = torch.library.opcheck(philox_mask, (state, [3, 5], 1 << 31, 2.0), test_utils=checks)
    advance = torch.library.opcheck(philox_advance, (state, 4), test_utils=checks)
    return {'mask': mask, 'advance': advance}


def test_invalid_metadata_refused():
    x = torch.ones(4)
    invalid = [lambda: dropout(x, torch.zeros(4), 0.5),
               lambda: dropout(x, torch.zeros(3, dtype=torch.int64), 0.5),
               lambda: dropout(x, torch.zeros(8, dtype=torch.int64)[::2], 0.5),
               lambda: dropout(x, make_rng_state(1), 1.0),
               lambda: dropout(x, make_rng_state(1), float('nan')),
               lambda: philox_advance(make_rng_state(1), -1)]
    for fn in invalid:
        try:
            fn()
        except ValueError:
            continue
        raise AssertionError('invalid RNG contract was accepted')
    return {'refusals': len(invalid)}


def run():
    torch.set_num_threads(1)
    results = {}
    for name, fn in list(globals().items()):
        if name.startswith('test_') and callable(fn):
            try:
                results[name] = {'passed': True, 'details': fn()}
            except Exception:
                results[name] = {'passed': False, 'traceback': traceback.format_exc()}
    return {'torch': torch.__version__, 'passed': all(row['passed'] for row in results.values()),
            'count': len(results), 'tests': results,
            'scope': 'CPU exact-state/custom-op/fake-AD capture checks; native qualification is separate'}


if __name__ == '__main__':
    result = run()
    print(json.dumps(result, indent=2))
    raise SystemExit(0 if result['passed'] else 1)
